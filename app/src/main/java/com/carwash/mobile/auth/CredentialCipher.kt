package com.carwash.mobile.auth

import java.util.Base64

fun interface CredentialEncoder {
    fun encode(plain: String): String
}

// Android no incluye RC2. Implementacion RC2-CBC con relleno PKCS7 (RFC 2268), compatible
// con FunctionsEncrip.Cifrado del WinForm: el API compara los valores ya cifrados.
object CredentialCipher : CredentialEncoder {
    private const val BLOCK = 8

    private val key = "C4rW4sh".toByteArray(Charsets.US_ASCII)
    private val iv = "20270430".toByteArray(Charsets.US_ASCII)


        0xc5, 0xf3, 0xdb, 0x47, 0xe5, 0xa5, 0x9c, 0x77, 0x0a, 0xa6, 0x20, 0x68, 0xfe, 0x7f, 0xc1, 0xad,
    )

    private val expandedKey: IntArray = expand(key)

    override fun encode(plain: String): String {
        val data = plain.toByteArray(Charsets.UTF_8)
        val padding = BLOCK - data.size % BLOCK
        val padded = data + ByteArray(padding) { padding.toByte() }
        val output = ByteArray(padded.size)
        var previous = iv
        for (offset in padded.indices step BLOCK) {
            val block = ByteArray(BLOCK) { (padded[offset + it].toInt() xor previous[it].toInt()).toByte() }
            previous = encryptBlock(block)
            previous.copyInto(output, offset)
        }
        return Base64.getEncoder().encodeToString(output)
    }

    private fun expand(key: ByteArray): IntArray {
        val length = key.size
        val bytes = IntArray(128)
        for (i in key.indices) bytes[i] = key[i].toInt() and 0xFF
        for (i in length until 128) bytes[i] = PI_TABLE[(bytes[i - 1] + bytes[i - length]) and 0xFF]
        // Longitud efectiva igual a la del WinForm: 8 * longitud de la clave (56 bits).
        bytes[128 - length] = PI_TABLE[bytes[128 - length]]
        for (i in 127 - length downTo 0) bytes[i] = PI_TABLE[bytes[i + 1] xor bytes[i + length]]
        return IntArray(64) { bytes[2 * it] or (bytes[2 * it + 1] shl 8) }
    }

    private fun encryptBlock(block: ByteArray): ByteArray {
        val r = IntArray(4) { (block[2 * it].toInt() and 0xFF) or ((block[2 * it + 1].toInt() and 0xFF) shl 8) }
        var j = 0
        for (round in 0 until 16) {
            r[0] = rotl(r[0] + expandedKey[j++] + (r[3] and r[2]) + (r[3].inv() and r[1]), 1)
            r[1] = rotl(r[1] + expandedKey[j++] + (r[0] and r[3]) + (r[0].inv() and r[2]), 2)
            r[2] = rotl(r[2] + expandedKey[j++] + (r[1] and r[0]) + (r[1].inv() and r[3]), 3)
            r[3] = rotl(r[3] + expandedKey[j++] + (r[2] and r[1]) + (r[2].inv() and r[0]), 5)
            if (round == 4 || round == 10) {
                for (i in 0 until 4) r[i] = (r[i] + expandedKey[r[(i + 3) % 4] and 63]) and 0xFFFF
            }
        }
        return ByteArray(BLOCK) { ((r[it / 2] shr (8 * (it % 2))) and 0xFF).toByte() }
    }

    private fun rotl(value: Int, bits: Int): Int {
        val v = value and 0xFFFF
        return ((v shl bits) or (v ushr (16 - bits))) and 0xFFFF
    }
}
